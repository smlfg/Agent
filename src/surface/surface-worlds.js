function buildWorld(raw) {
  const validated = validateBonePatch(raw.patch, DEFAULT_BONES);
  const guarded = ensureWcagContrast(validated.nextBones);
  return Object.freeze({
    id: raw.id,
    name: raw.name,
    feeling: raw.feeling,
    bones: Object.freeze(guarded),
    rejected: validated.rejected,
  });
}

export const WORLD_LIST = Object.freeze(RAW_WORLDS.map(buildWorld));

export const SURFACE_WORLDS = Object.freeze(
  Object.fromEntries(WORLD_LIST.map((world) => [world.id, world])),
);

export function getWorldById(id) {
  if (typeof id !== 'string') return null;
  const key = id.trim().toLowerCase();
  return SURFACE_WORLDS[key] ?? null;
}

