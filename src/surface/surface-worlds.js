const SURPRISE_TRIGGER = /(?<![\p{L}\p{N}_])(überrasch\s*mich|experimentier[\p{L}\p{N}_]*|mehr\s+varianz|nächste\s+welt|etwas\s+neues|austoben|tobe?\s+dich\s+aus|zufällige\s+welt|surprise\s+me)(?![\p{L}\p{N}_])/iu;

/**
 * Match a conversational request to either a curated world or high-temperature creative mutation.
 */
export function matchWorldFromUtterance(text) {
  const s = String(text ?? '').trim();
  if (!s) return null;

  for (const [id, re] of WORLD_TRIGGERS) {
    if (re.test(s)) {
      return { kind: 'world', world: SURFACE_WORLDS[id] };
    }
  }

  if (SURPRISE_TRIGGER.test(s)) {
    return { kind: 'surprise' };
  }

  return null;
}
