/**
 * Resolve any eye state or alias into one of EYE_STATES.
 * Unknown values safely fall back to 'present'.
 *
 * @param {string} name
 * @returns {string}
 */
export function normalizeEyeState(name) {
  if (typeof name !== 'string') return 'present';
  const key = name.trim().toLowerCase();
  if (Object.hasOwn(EYE_STATE_PROFILES, key)) return key;
  if (Object.hasOwn(STATE_ALIASES, key)) return STATE_ALIASES[key];
  return 'present';
}

